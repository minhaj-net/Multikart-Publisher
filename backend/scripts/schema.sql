CREATE TABLE IF NOT EXISTS countries (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  currency VARCHAR(50) NULL,
  currency_symbol VARCHAR(10) NULL,
